#!/usr/bin/env python3
"""Generates each platform's colour tokens from resources/design-tokens.json.

Outputs (committed, never edited by hand):
  iosApp/Resources/Colors.xcassets/<name>.colorset   light and dark appearances
  androidApp/src/main/kotlin/.../designsystem/GeneratedColors.kt
Run with --check in CI to fail when a generated file is out of date.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = json.loads((ROOT / "resources/design-tokens.json").read_text())["colors"]
IOS = ROOT / "iosApp/Resources/Colors.xcassets"
ANDROID = ROOT / "androidApp/src/main/kotlin/com/example/daysmark/android/designsystem/GeneratedColors.kt"


def components(hex_color):
    value = hex_color.lstrip("#")
    return {"alpha": "1.000", "red": f"0x{value[0:2]}", "green": f"0x{value[2:4]}", "blue": f"0x{value[4:6]}"}


def colorset(token):
    light = {"color": {"color-space": "srgb", "components": components(token["light"])}, "idiom": "universal"}
    dark = {
        "appearances": [{"appearance": "luminosity", "value": "dark"}],
        "color": {"color-space": "srgb", "components": components(token["dark"])},
        "idiom": "universal",
    }
    return json.dumps({"colors": [light, dark], "info": {"author": "xcode", "version": 1}}, indent=2) + "\n"


def kotlin():
    def palette(mode):
        return "\n".join(
            f"        {name} = Color(0xFF{token[mode].lstrip('#')}),"
            for name, token in TOKENS.items()
        )

    fields = "\n".join(f"    val {name}: Color," for name in TOKENS)
    return f"""// Generated by scripts/generate-design-tokens.py from resources/design-tokens.json. Do not edit.
package com.example.daysmark.android.designsystem

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

@Immutable
data class DaysmarkColors(
{fields}
) {{
    companion object {{
        val Light =
            DaysmarkColors(
{palette("light").replace("        ", "                ")}
            )

        val Dark =
            DaysmarkColors(
{palette("dark").replace("        ", "                ")}
            )
    }}
}}
"""


def outputs():
    files = {IOS / "Contents.json": json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n"}
    for name, token in TOKENS.items():
        files[IOS / f"{name}.colorset/Contents.json"] = colorset(token)
    files[ANDROID] = kotlin()
    return files


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs().items():
        if path.exists() and path.read_text() == text:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        sys.exit("Out of date, run scripts/generate-design-tokens.py:\n  " + "\n  ".join(stale))


if __name__ == "__main__":
    main()
